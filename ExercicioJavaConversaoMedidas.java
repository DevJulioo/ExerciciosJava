public class ExercicioJavaConversaoMedidas {
    public static void main(String[] args) {
        
        // Variável que armazena o metro
        int unidadeMedidaMetro = 2;

        //Variável que calcula a conversão de M para CM
        int unidadeMedidaConvertidaCM = unidadeMedidaMetro * 100;

        // Exibição do resultado na tela
        System.out.println("O metro convertido para centímetros é: " + unidadeMedidaConvertidaCM);
    }
}
